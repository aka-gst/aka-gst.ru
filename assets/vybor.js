// Страница выбора отправляет выбор САМА, кликом — правило 30е.
//
// Стоячее требование Сергея, повторённое 5 сентября 2026: «Я просил, чтобы я
// кликал по выбору — вам сразу уходил ответ!» Он просил это и раньше; страницу
// выбора голосов всё равно сделали текстом на экране, и ответ пришлось читать
// с его скриншота. Больше так не делаем.
//
// ЗАЧЕМ ОДИН ФАЙЛ НА ВЕСЬ САЙТ. Страниц выбора будет много — голоса, графика,
// пробы на слух, галочки в ежедневном отчёте. Код отправки, размноженный по
// ним, это правило 27: первая же починка ляжет в одну копию из пяти, а
// остальные будут молча слать не туда.
//
// КАК ПОДКЛЮЧИТЬ (Рот, это всё, что нужно):
//
//   <script defer src="/assets/vybor.js" data-vybor-opros="grafika-0509"></script>
//
//   <input type="checkbox" data-vybor="shar-krasnyy">
//   <button data-vybor="golos" data-vybor-znachenie="A">Вариант A</button>
//
// `data-vybor` — что выбирают, `data-vybor-znachenie` — что именно выбрали
// (у галочки берётся её состояние). Всё остальное берёт на себя этот файл.
//
// СТРАНИЦА МОЖЕТ ЛЕЖАТЬ ЛОКАЛЬНО. Проверено 5 сентября живым браузером на
// настоящей `file://` странице: запрос доходит, политика источников его не
// закрывает. Это важно, потому что отчётные страницы в публичный корень не
// кладут — в них имена и цитаты (правило 28а).
//
// ЧТО НЕ УХОДИТ: ничего про человека. Только что выбирали и что выбрали.
// Ни имён, ни текста заметок, ни адреса страницы, ни содержимого отчёта.
//
// «СДЕЛАНО» = СОБЫТИЕ ДОШЛО (правило 30). Поэтому отметка «принято» ставится
// ТОЛЬКО после ответа коллектора. Галочка, зеленеющая независимо от исхода, —
// это ровно тот тихий пропуск, от которого правило 7р.

(() => {
  const скрипт = document.currentScript
    || document.querySelector('script[data-vybor-opros]');
  const ОПРОС = скрипт?.dataset.vyborOpros || 'bez-imeni';
  const КОЛЛЕКТОР = 'https://aka-gst.ru/pulse/api/send';
  const САЙТ = 'de024048-c4c3-4639-bbdf-808c558f6d71';

  // Метка обязательна: наши прогоны и пробы неотличимы от людских, потому что
  // идут теми же путями. Префикс позволяет отфильтровать их при чтении, а не
  // разбирать потом вручную (правило 30).
  const ИМЯ = (что) => `vybor:${ОПРОС}:${что}`;

  const послать = async (что, значение) => {
    const ответ = await fetch(КОЛЛЕКТОР, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        type: 'event',
        payload: {
          website: САЙТ,
          hostname: 'vybor',            // не адрес страницы: она бывает локальной
          url: `/vybor/${ОПРОС}`,       // и в адресе не должно быть ничего личного
          name: ИМЯ(что),
          data: { znachenie: String(значение) },
        },
      }),
    });
    if (!ответ.ok) throw new Error(`коллектор ответил ${ответ.status}`);
    return true;
  };

  // Отметка рисуется рядом с элементом, чтобы человек видел исход, а не гадал.
  const пометить = (эл, состояние, текст) => {
    let метка = эл.parentElement?.querySelector('[data-vybor-metka]');
    if (!метка) {
      метка = document.createElement('span');
      метка.setAttribute('data-vybor-metka', '');
      метка.style.cssText = 'margin-left:8px;font-size:12px;vertical-align:middle';
      эл.insertAdjacentElement('afterend', метка);
    }
    метка.textContent = текст;
    метка.style.color = { идёт: '#9aa4ae', принято: '#3ddc84', ошибка: '#ff6b6b' }[состояние];
  };

  const отправить = async (эл) => {
    const что = эл.dataset.vybor;
    const значение = эл.type === 'checkbox'
      ? (эл.checked ? 'da' : 'net')
      : (эл.dataset.vyborZnachenie ?? 'da');
    пометить(эл, 'идёт', '…');
    try {
      await послать(что, значение);
      пометить(эл, 'принято', '✓ ушло');
    } catch (e) {
      // Громко, но не молча-зелено: человек должен знать, что ответ НЕ ушёл,
      // иначе он уйдёт уверенный, что выбор сделан, а у нас будет пусто.
      пометить(эл, 'ошибка', '× не ушло, нажмите ещё раз');
      console.warn('[vybor] отправка не удалась:', e.message);
    }
  };

  const элементы = [...document.querySelectorAll('[data-vybor]')];
  if (!элементы.length) {
    // Громко для нас, молча для человека: скрипт подключили, а размечать
    // забыли — это наша ошибка, и она обязана быть видна (правило 7р).
    console.warn('[vybor] на странице нет ни одного элемента с data-vybor — опрос', ОПРОС);
    return;
  }
  for (const эл of элементы) {
    эл.addEventListener(эл.type === 'checkbox' ? 'change' : 'click', () => отправить(эл));
  }
  console.info(`[vybor] опрос «${ОПРОС}», элементов: ${элементы.length}`);
})();
