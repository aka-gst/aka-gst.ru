async function запрос(url, { тело = false } = {}) {
  for (let попытка = 1; попытка <= 3; попытка++) {
    try {
      const c = AbortSignal.timeout(25000);
      const r = await fetch(url, { redirect: 'manual', signal: c });
      return { код: r.status, тело: тело ? await r.text() : '' };
    } catch {
      if (попытка < 3) await new Promise(r => setTimeout(r, 800));
    }
  }
  return { код: 0, тело: '' };
}

async function пачкой(список, работа, разом = 6) {
  const итог = new Map();
  let i = 0;
  const нить = async () => {
    while (i < список.length) {
      const мой = список[i++];
      итог.set(мой, await работа(мой));
    }
  };
  await Promise.all(Array.from({ length: Math.min(разом, список.length) }, нить));
  return итог;
}

// ── видимые ссылки: разбор стеком, а не одним grep ────────────────────────
// grep по href нашёл бы и строку внутри <script>, и заготовку в <template>,
// и закомментированный кусок. Всё это не ссылки: человек по ним не нажмёт.
const ПУСТЫЕ = new Set(['img', 'br', 'hr', 'input', 'meta', 'link', 'source',
  'track', 'wbr', 'area', 'col', 'embed', 'param', 'path', 'circle', 'rect',
  'use', 'stop', 'line', 'polygon', 'polyline', 'ellipse']);

function видимыеСсылки(html) {
  // мёртвая разметка вон
  let h = html
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<script\b[\s\S]*?<\/script>/gi, '')
    .replace(/<style\b[\s\S]*?<\/style>/gi, '')
    .replace(/<template\b[\s\S]*?<\/template>/gi, '')
    .replace(/<noscript\b[\s\S]*?<\/noscript>/gi, '');

  const ссылки = [];
  const стек = [];           // {тег, прячет, вкладка}
  const тег = /<(\/?)([a-zA-Z][a-zA-Z0-9:-]*)((?:"[^"]*"|'[^']*'|[^>"'])*?)(\/?)>/g;
  let m;
  while ((m = тег.exec(h))) {
    const закрывающий = m[1] === '/';
    const имя = m[2].toLowerCase();
    const атрибуты = m[3] || '';
    const самозакрытый = m[4] === '/';

    if (закрывающий) {
      for (let i = стек.length - 1; i >= 0; i--) {
        if (стек[i].тег === имя) { стек.length = i; break; }
      }
      continue;
    }

    const прячет = /\shidden(?=[\s>=/])/i.test(атрибуты)
      || /aria-hidden\s*=\s*["']true["']/i.test(атрибуты)
      || /style\s*=\s*["'][^"']*(display\s*:\s*none|visibility\s*:\s*hidden)/i.test(атрибуты);
    // Скрытая вкладка открывается одним касанием — это достижимо (правило 29б).
    const вкладка = /role\s*=\s*["']tabpanel["']/i.test(атрибуты)
      || /\bdata-[a-z-]*panel\s*=/i.test(атрибуты);

    if (имя === 'a' || имя === 'area') {
      const h1 = /href\s*=\s*"([^"]*)"/i.exec(атрибуты) || /href\s*=\s*'([^']*)'/i.exec(атрибуты);
      if (h1) {
        // Ссылка недостижима, только если её прячет что-то, что НЕ вкладка.
        const глухо = стек.some(у => у.прячет && !у.вкладка)
          || (прячет && !вкладка);
        ссылки.push({ href: h1[1], глухо });
      }
    }

    if (!самозакрытый && !ПУСТЫЕ.has(имя)) стек.push({ тег: имя, прячет, вкладка });
  }
  return ссылки;
}

// Первый сегмент пути. Внешние адреса и почта отбрасываются, свой домен —
// внутренний. Строку запроса и якорь режем, но ПОСЛЕ того, как убедились,
// что это наш адрес: инструмент, режущий адрес до разбора, теряет искомое.
function сегмент(href, база) {
  let u;
  try { u = new URL(href, база + '/'); } catch { return null; }
  if (!/^https?:$/.test(u.protocol)) return null;
  if (u.origin !== new URL(база).origin) return null;
  const части = u.pathname.split('/').filter(Boolean);
  return части.length ? decodeURIComponent(части[0]).toLowerCase() : null;
}

// ── список «лежит на сервере»: четыре источника, потом живая проверка ─────
function изКорняПоSSH() {
  try {
    const out = execFileSync('ssh',
      ['-o', 'ConnectTimeout=15', '-o', 'BatchMode=yes', SSH_ХОСТ, `ls -1 ${КОРЕНЬ_САЙТА}`],
      { encoding: 'utf8', timeout: 30000, stdio: ['ignore', 'pipe', 'ignore'] });
    return out.split('\n').map(s => s.trim()).filter(Boolean);
  } catch { return null; }
}

function изCaddyПоSSH() {
  try {
    const out = execFileSync('ssh',
      ['-o', 'ConnectTimeout=15', '-o', 'BatchMode=yes', SSH_ХОСТ,
        `grep -oE 'handle_path /[a-zA-Z0-9_-]+/' ${КОРЕНЬ_САЙТА}/../Caddyfile || true`],
      { encoding: 'utf8', timeout: 30000, stdio: ['ignore', 'pipe', 'ignore'] });
    return out.split('\n').map(s => (/handle_path \/([^/]+)\//.exec(s) || [])[1]).filter(Boolean);
  } catch { return null; }
}

function изМестногоCaddyfile() {
  const п = join(КОРЕНЬ, 'Caddyfile');
  if (!existsSync(п)) return [];
  return [...readFileSync(п, 'utf8').matchAll(/handle_path \/([a-zA-Z0-9_-]+)\//g)].map(m => m[1]);
}

function изМестногоДерева() {
  return readdirSync(КОРЕНЬ, { withFileTypes: true })
    .filter(d => d.isDirectory() && !d.name.startsWith('.'))
    .filter(d => existsSync(join(КОРЕНЬ, d.name, 'index.html')))
    .map(d => d.name);
}

