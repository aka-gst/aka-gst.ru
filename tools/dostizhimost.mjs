// Достижимость: на всё ли, что лежит на сервере, есть путь с витрины.
//
// Правило владельца от 1 сентября 2026: «надо чтоб можно было попасть на всё,
// что есть на сайте!! это важно». Повод — NEON CLAW: игра лежала на /claw/ и
// честно отдавала 200 целую неделю, а карточки на витрине не было вовсе.
// Попасть можно было только по прямому адресу, если ты его знаешь.
//
//   node tools/dostizhimost.mjs                     полная сверка по бою
//   node tools/dostizhimost.mjs --tolko claw        сверка одного пути
//   node tools/dostizhimost.mjs --isklyucheniya "leela zoo"   названные владельцем
//   node tools/dostizhimost.mjs --adres https://...  другой адрес
//
// Код выхода: 0 — зелено, 1 — красно, 2 — проверить не удалось.
// Третий код обязателен: «сеть не ответила» это НЕ «всё хорошо».
//
// ЧТО ЗДЕСЬ ВАЖНО ЗНАТЬ, ЧТОБЫ НЕ ПЕРЕОТКРЫВАТЬ.
//
// 1. Сверяются ДВА списка, и расхождение в любую сторону — беда.
//    «Лежит и не видно» — человек не найдёт. «Видно и не лежит» — упрётся
//    в 404. Проверка одной стороны ловит половину бед.
//
// 2. Список «лежит на сервере» нельзя собрать одним источником. Корень
//    сайта (/opt/zakriva/caddy/site) не знает про игры, которые Caddy отдаёт
//    из отдельных корней через handle_path: /tetcolor/, /naotmash/,
//    /hotline-abakan/, /coin/, /lines/ в листинге корня ОТСУТСТВУЮТ, а на
//    сайте работают. Поэтому источников четыре, и каждый ответ проверяется
//    живым запросом: в список попадает только то, что реально отдало 200.
//
// 3. Искать надо ОТРИЦАНИЕМ, а не по словарю названий. Кнопка выхода у нас
//    называется «НА САЙТ», а не «на главную», и словарный поиск её терял.
//    Здесь тот же принцип: не ищем слова, а спрашиваем — есть ли ВИДИМАЯ
//    ссылка, ведущая на этот путь. Видимая значит настоящий <a href> в живой
//    разметке, а не строка в скрипте, не заготовка в <template> и не
//    закомментированный кусок.
//
// 4. Скрытая вкладка — это НЕ недостижимость. Правило 29б: дверь считается
//    достижимой, если до неё не больше двух касаний. Ссылка внутри
//    role="tabpanel" с атрибутом hidden открывается одним нажатием по
//    вкладке, поэтому засчитывается. А вот display:none без вкладки — нет.
//    Разбор ведётся стеком тегов, чтобы знать, ВНУТРИ чего лежит ссылка.
//
// 5. Обход витрины — на глубину один: главная плюс страницы, на которые она
//    ведёт. Это и есть «два касания» из правила 29б, только с другой стороны.
//
// 6. У проверки ЕСТЬ ОБА ИСХОДА, и это доказано, а не заявлено:
//      node tools/dostizhimost.mjs --tolko claw           → зелено
//      node tools/dostizhimost.mjs --tolko psy-admin-v2   → красно
//    Оба контроля идут по настоящему бою и настоящему разбору разметки —
//    сужается только предмет сверки. Проверка на выдуманных данных
//    доказывает работу выдумки, а не проверки.
//
// 7. Переадресация (30x) — не вещь, а дверь. /knb/, /worm/, /udar/,
//    /neon-claw/ ведут на новые адреса и оставлены для тех, у кого старый
//    в закладках. Требовать на них ссылку с витрины неверно.

