#!/usr/bin/env sh
# Страница «Дневника пути» на /way/ — из репозитория Рук в дерево сайта.
#
# Почему отдельный скрипт, а не «скопировал руками»: страницу ведут Руки в
# своём репозитории (~/dev/dnevnik-puti), а выкладывает сайт. Правило «один
# репозиторий — одна сессия» держится ровно до первой правки чужой рукой,
# поэтому здесь копирование в одну сторону и отметка о том, ЧТО именно
# скопировано: sha их коммита ложится в way/versiya.txt, и сверка боя идёт
# по нему, а не по «вроде выложил».
#
#   sh tools/vylozhit-way.sh <sha-коммита-Рук>
# Имена переменных ЛАТИНИЦЕЙ. POSIX-оболочка кириллические имена не
# принимает и падает на первом же присваивании: «ИСТОЧНИК=…: No such file or
# directory». В своде это правило записано давно, в наборе тестов сайта на
# него есть проверка, и я всё равно наступил на него сейчас.
set -eu

SHA="${1:-}"
SRC="${DNEVNIK_SRC:-$HOME/dev/dnevnik-puti}"
HERE="$(cd "$(dirname "$0")/.." && pwd)"

[ -n "$SHA" ] || { echo "!! назовите sha коммита Рук: sh tools/vylozhit-way.sh <sha>" >&2; exit 1; }
[ -d "$SRC" ] || { echo "!! нет репозитория $SRC" >&2; exit 1; }
[ -f "$SRC/index.html" ] || { echo "!! в $SRC нет index.html" >&2; exit 1; }

# Сверяем, что у них в дереве действительно тот коммит, о котором сказали:
# иначе выложим не то, о чём договорились, и сверка по бою будет врать.
HEAD_SHA=$(cd "$SRC" && git rev-parse --short HEAD)

# Требуем, чтобы названный коммит СУЩЕСТВОВАЛ в их истории, а не совпадал с
# их HEAD. Равенства требовала первая версия — и оно ломалось всякий раз,
# когда автор продолжал работать после того, как назвал sha. Это нормальная
# жизнь: строку «готово, коммит такой-то» пишут, а работу не останавливают.
# Важно другое: что публикуется настоящий коммит из истории, а не брошенная
# ветка и не опечатка.
if ! (cd "$SRC" && git cat-file -e "$SHA^{commit}" 2>/dev/null); then
  echo "!! коммита $SHA нет в репозитории автора — не выкладываю" >&2; exit 1
fi
if ! (cd "$SRC" && git merge-base --is-ancestor "$SHA" HEAD 2>/dev/null); then
  echo "!! коммит $SHA не входит в текущую ветку автора (сейчас $HEAD_SHA) — не выкладываю" >&2; exit 1
fi
[ "$SHA" = "$HEAD_SHA" ] || echo "  прим.: у автора уже $HEAD_SHA, выкладываю названный $SHA"
# Берём файл ИЗ НАЗВАННОГО КОММИТА, а не из рабочего дерева.
#
# Первая версия копировала рабочий файл и потому отказывалась, когда автор
# продолжал править после того, как назвал sha, — а это нормальная жизнь:
# строку «готово, коммит такой-то» пишут, а работу не останавливают. Отказ
# был честным, но чинил не то. Теперь публикуется ровно то, что названо, и
# отметка versiya.txt описывает СОДЕРЖИМОЕ, а не намерение.
DIRTY=$(cd "$SRC" && git status --porcelain -- index.html)
[ -z "$DIRTY" ] || echo "  прим.: у автора поверх $HEAD_SHA есть незакоммиченные правки — выкладываю коммит, не дерево"

# Публикуем только то, что нужно странице: одна разметка и отметка версии.
mkdir -p "$HERE/way"
(cd "$SRC" && git show "$SHA:index.html") > "$HERE/way/index.html"
printf '%s\n' "$SHA" > "$HERE/way/versiya.txt"

# Проверка того, что публикуем: страница уходит наружу, и читать её надо до,
# а не после. Красное здесь — повод не выкладывать, а не примечание.
node - "$HERE/way/index.html" <<'JS'
import { readFileSync } from 'node:fs';
const html = readFileSync(process.argv[2], 'utf8');
const беды = [
  [!/name=["']robots["'][^>]*noindex/i.test(html), 'нет noindex — страницу проиндексируют'],
  // Счётчик обязателен по решению Мозга 6 сентября: это не трекер перед
  // клиентом, а наш собственный /pulse с первой стороны и без личных данных.
  // Он отвечает на главный вопрос продажи — открыли ли ссылку сами после
  // встречи и вернулись ли. Без него страница молчит о том единственном,
  // ради чего её показывают.
  [!/\/pulse\/script\.js/.test(html), 'нет счётчика /pulse — страница не скажет, вернулись ли люди'],
  // Внешние адреса ищем, но счётчик и шрифты сюда не попадают: он с первой
  // стороны, путь от корня.
  [/https?:\/\//i.test(html), 'внешний адрес в разметке'],
  [/<input|<textarea/i.test(html), 'поле ввода на странице без формы'],
].filter(([плохо]) => плохо).map(([, имя]) => имя);
if (беды.length) { console.error('!! ' + беды.join('; ')); process.exit(1); }
console.log('  страница проверена: noindex на месте, внешних адресов и полей нет');
JS

echo "  выложен коммит $SHA в way/, отметка версии записана"
echo "  дальше: добавить way в PAYLOAD в deploy.sh (если ещё нет) и sh deploy.sh --go"
