// Сверяет возраст кадра на витрине с последней правкой самой игры.
//
//   node tools/svezhest-kadrov.mjs
//
// Смотрит и на кадры, и на петли. Петля стареет так же, как кадр, и даже
// быстрее: она показывает не вид игры, а её правила в действии. У ТехноМагии
// за один вечер трижды менялись правила — щиток, двери, ветер, — и петля,
// снятая час назад, могла перестать быть правдой.
//
// Зачем. 30 августа владелец открыл сайт и спросил: «а чо на сайте не
// обновилось-то ничо?» Он был прав: три игры за ночь переделали, а карточки
// показывали кадры шестичасовой давности — ТехноМагия обещала изометрию,
// которую убрали, у Наотмашь на кадре была игра, которой больше нет.
//
// Заметил это человек. Должна замечать машина: отставание витрины видно
// сравнением двух дат, и его незачем ловить глазами.
//
// Меряем по дате последнего коммита игры, а не по дате правки файлов: файлы
// трогает кто угодно (сборка, редактор, rsync), а коммит означает, что игра
// действительно изменилась.
//
// Ругается мягко и по умолчанию возвращает ноль. Сравниваются ДАТЫ, а не
// содержимое: коммит после кадра не обязан менять картинку. Первый же прогон
// это показал — Тетколор «отстал» из-за коммита про звук, где визуала не было
// вовсе. Страж, который ругается по пустякам, начнут обходить, и он
// промолчит там, где важно. С --strict возвращает единицу — для тех, кто
// захочет повесить это на выкладку.

import { spawnSync } from 'node:child_process';
import { statSync, existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { PLAN } from './games-plan.mjs';

// Карточка может обходиться без кадра — у ПЕРИМЕТРА он не снят намеренно:
// игра тёмная по замыслу, и вслепую представительный кадр не добывается.
// «Кадра нет» и «кадр отстал» — разные вещи, и путать их нельзя.
const карточки = JSON.parse(
  readFileSync(new URL('../data/projects.json', import.meta.url), 'utf8')
).projects;
const ждётКадр = (id) => {
  const c = карточки.find((p) => p.analytics?.slug === id || p.id === id);
  return Boolean(c?.shots?.length);
};

const строго = process.argv.includes('--strict');

const дом = new URL('../..', import.meta.url).pathname;
const сайт = new URL('..', import.meta.url).pathname;

const коммит = (репо) => {
  const r = spawnSync('git', ['-C', join(дом, репо), 'log', '-1', '--format=%ct'], { encoding: 'utf8' });
  if (r.status !== 0) return null;
  const t = Number(r.stdout.trim());
  return Number.isFinite(t) && t > 0 ? t * 1000 : null;
};

const дата = (мс) => new Date(мс).toLocaleString('ru-RU', { day: '2-digit', month: '2-digit', hour: '2-digit', minute: '2-digit' });

let отстали = 0;
let немеряно = 0;
console.log('игра         кадр снят         игра правлена      кадр                 петля');
for (const game of PLAN) {
  const петля = join(сайт, 'assets/clips', `clip-${game.id}.mp4`);
  const кадр = join(сайт, 'assets/shots', `game-${game.id}.jpg`);
  if (!existsSync(кадр)) {
    const ждём = ждётКадр(game.id);
    console.log(`${game.id.padEnd(12)} кадра нет${ждём ? ' — а карточка на него ссылается' : ' (карточка и не ждёт)'}`);
    if (ждём) отстали += 1;
    continue;
  }
  const снят = statSync(кадр).mtimeMs;
  if (!game.repo) { console.log(`${game.id.padEnd(12)} ${дата(снят).padEnd(17)} репозиторий не указан`); немеряно += 1; continue; }
  const правлена = коммит(game.repo);
  if (правлена === null) {
    // Один удар лежит папкой без гита — сравнивать не с чем. Молчать об этом
    // нельзя: «проверка прошла» и «проверять было нечем» — разные вещи.
    console.log(`${game.id.padEnd(12)} ${дата(снят).padEnd(17)} — у ${game.repo} нет гита, сверить не с чем`);
    немеряно += 1;
    continue;
  }
  const плохо = снят < правлена;
  if (плохо) отстали += 1;

  // Петля отдельной строкой: у неё своя дата и своя судьба. Карточка может
  // жить со свежим кадром и протухшей петлёй — снаружи это выглядит хуже
  // старого кадра, потому что петля обещает поведение, а не вид.
  let проПетлю = 'петли нет';
  if (existsSync(петля)) {
    const снята = statSync(петля).mtimeMs;
    const стара = снята < правлена;
    if (стара) отстали += 1;
    проПетлю = `петля ${дата(снята)}${стара ? ' ← СТАРШЕ ИГРЫ' : ''}`;
  }
  console.log(`${game.id.padEnd(12)} ${дата(снят).padEnd(17)} ${дата(правлена).padEnd(17)} ${(плохо ? '← КАДР СТАРШЕ ИГРЫ' : 'ok').padEnd(20)} ${проПетлю}`);
}

console.log('');
if (немеряно) console.log(`не с чем сверить: ${немеряно}`);
if (отстали) {
  console.log(`посмотреть глазами по ${отстали}: node tools/shoot-games.mjs <id> и node tools/record-games.mjs <id>`);
  console.log('(сравнивались даты, а не картинки: коммит мог не трогать вид)');
  if (строго) process.exit(1);
} else {
  console.log('ни один кадр не старше своей игры');
}
