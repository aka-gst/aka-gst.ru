#!/usr/bin/env sh
# Что незакоммиченного уедет на бой вместе с выкладкой.
#
# Повод, 6 сентября 2026: с моей выкладкой на бой уехала чужая
# незакоммиченная правка — assets/app.js с политикой адресов и
# sync-portfolio.sh, изменённые за минуты до отправки другой сессией. Код
# оказался рабочим, вреда не было, но решение «показать это людям сейчас»
# принимал не автор.
#
# Причина не в невнимательности: ВЫКЛАДКА ШЛЁТ ФАЙЛЫ С ДИСКА, А НЕ ИЗ
# КОММИТА. Значит «в main чисто» не говорит ничего о том, что уедет, а в
# общем дереве всегда кто-то работает. Помнить об этом должен скрипт.
#
#   sh tools/chuzhoe-v-dereve.sh <пути выкладки...>
#
# Код 0 — незакоммиченного в выкладке нет. Код 1 — есть, список в выводе.
#
# Что НЕ считается чужой работой и почему:
#   * файлы, которые пересобирает build.mjs, — это наш собственный вывод,
#     он меняется каждой сборкой, и краснеть на нём значит краснеть всегда
#     (правило 7и: проверка без зелёного исхода живёт до первого отключения);
#   * файлы под .gitignore — они незакоммичены НАРОЧНО: страницы Орион-С и
#     страница теста Торгаша не кладутся в открытый репозиторий, но
#     выкладываются. `git status` их и не показывает.
#
# Отличить «своё» от «чужого» надёжно нельзя: git не помнит, кто правил
# файл до коммита. Поэтому проверка не гадает, а показывает список и
# требует решения — оно дешевле ошибки.
set -eu

cd "$(dirname "$0")/.."

# Вывод сборки: build.mjs переписывает это сам, каждый раз.
SBORKA="index.html
404.html
503.html
sitemap-pages.xml
assets/covers/proizvodnye.json
rasskazy/
utro/
en/"

[ $# -gt 0 ] || { echo "!! не дано ни одного пути выкладки" >&2; exit 2; }

VSE=$(git status --porcelain -- "$@" | sed 's/^...//' | sed 's/ -> .*//')

NAYDENO=""
for f in $VSE; do
  propustit=0
  for s in $SBORKA; do
    case "$f" in
      "$s"|"$s"*) propustit=1; break ;;
    esac
  done
  [ "$propustit" = 1 ] && continue
  NAYDENO="$NAYDENO$f
"
done

NAYDENO=$(printf '%s' "$NAYDENO" | sed '/^$/d')

if [ -z "$NAYDENO" ]; then
  echo "незакоммиченного в выкладке нет"
  exit 0
fi

echo "!! в выкладку попадёт незакоммиченное — оно уедет на бой с диска:" >&2
printf '%s\n' "$NAYDENO" | while read -r f; do
  [ -n "$f" ] || continue
  kogda=$(stat -f '%Sm' -t '%d.%m %H:%M' "$f" 2>/dev/null || echo '?')
  echo "   $f   (правлен $kogda)" >&2
done
echo "!! чужую работу выкладывать нельзя без слова автора: спросите в чате команды." >&2
echo "!! своё — закоммитьте, тогда видно, что именно уехало." >&2
exit 1
