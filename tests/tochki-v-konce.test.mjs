import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

// Сергей 6 сентября 2026: «точки в конце предложения убери — ты знаешь, что я
// это не люблю везде; в Dharma вижу точку в конце, в Gateway вижу точку в
// конце». «Везде» — значит правило, а не две правки.
//
// Само снятие делает сборка (проход снятьТочки в build.mjs), а этот тест
// стережёт результат: правило, которое держится на внимательности, живёт до
// первой правки чужой рукой.
//
// Классы прицельные — только то, что человек читает как подпись. Абзацы
// страниц, главы «Пути» и рассказы сюда не входят: там точка на месте.
const КЛАССЫ = ['gcard-text', 'card-text', 'tagline', 'work-duet-note', 'work-put-sub',
  'gw-case', 'gw-note', 'mast-stamp', 'kicker', 'job-role', 'shot-caption'];

const КОНТЕЙНЕРЫ = ['work-gateway-copy', 'work-dharma-copy'];

// Меряем ТЕКСТ, который видит человек: содержимое элемента без тегов.
// Первая версия этой меры искала только элементы БЕЗ вложенных тегов и
// только по классам — и показывала ноль ровно на тех строках, куда Сергей
// ткнул пальцем: у подписей внутри стрелка <i>, а описания шлюза и Dharma
// лежат в <p> вовсе без класса. Мера смотрела не на предмет.
const строки = (html) => {
  const собрано = [];
  for (const кл of КЛАССЫ) {
    const о = new RegExp(`<(\\w+)[^>]*class="[^"]*\\b${кл}\\b[^"]*"[^>]*>((?:(?!</\\1>)[\\s\\S])*?)</\\1>`, 'g');
    for (const m of html.matchAll(о)) собрано.push(m[2].replace(/<[^>]+>/g, '').trim());
  }
  for (const конт of КОНТЕЙНЕРЫ) {
    const о = new RegExp(`<div[^>]*class="[^"]*\\b${конт}\\b[^"]*"[^>]*>((?:(?!</div>)[\\s\\S])*)`, 'g');
    for (const m of html.matchAll(о)) {
      for (const п of m[1].matchAll(/<p(?![^>]*class="kicker")[^>]*>((?:(?!<\/p>)[\s\S])*?)<\/p>/g)) {
        собрано.push(п[1].replace(/<[^>]+>/g, '').trim());
      }
    }
  }
  return собрано.filter(Boolean);
};

test('в конце коротких строк карточек нет точки', () => {
  const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
  const все = строки(html);
  // Положительный контроль: без него тест зелен на пустоте — не нашли ни
  // одной строки и радостно отчитались, что точек нет.
  assert.ok(все.length >= 28, `строк карточек найдено ${все.length} — проверять нечего, мера смотрит не туда`);
  const сТочкой = все.filter((с) => с.endsWith('.') && !с.endsWith('..'));
  assert.deepEqual(сТочкой, [], `строки с точкой в конце: ${сТочкой.join(' | ')}`);

  // Отрицательный контроль: та же мера обязана краснеть на подсаженной точке.
  const подсажено = строки(html.replace(/(<p class="work-put-sub">[^<]*)</, '$1.<'));
  assert.ok(подсажено.some((с) => с.endsWith('.')), 'мера не видит точку даже когда её поставили — она слепая');
});

test('вопросительный и восклицательный знаки не трогаются', () => {
  const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
  const все = строки(html);
  assert.ok(все.some((с) => с.endsWith('?')), 'строка с вопросом пропала — правило про точку срезало лишнее');
});
