// Фраза Сергея на карточке QueQuest обязана стоять ПОСИМВОЛЬНО как он её
// продиктовал. Это не стилистика, это правило 35а: авторский текст не
// редактируется молча, ни одного слова.
//
// Повод — дважды. 6 сентября её заменили коммитом 9cd50d3, я вернул в
// 2870f18; вечером того же дня её заменили СНОВА, коммитом 4ae8908. Оба раза
// правка выглядела улучшением описания, оба раза это была подмена его слов.
// Договорённость не сработала дважды — значит стеречь должна проверка.
//
// Эталон лежит отдельным файлом data/fraza-quequest.txt: сравнивать разметку
// с самой собой бессмысленно, нужен независимый источник правды.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const корень = join(dirname(fileURLToPath(import.meta.url)), '..');
const эталон = readFileSync(join(корень, 'data/fraza-quequest.txt'), 'utf8').trim();

// Чистая проверка, чтобы её саму можно было завалить нарочно.
export const беды = (html, образец) => {
  const б = [];
  const строки = [...html.matchAll(/<p class="tagline">([^<]*)<\/p>/g)].map((m) => m[1]);
  if (!строки.length) б.push('на странице нет ни одной строки tagline — ищем не там');
  else if (!строки.includes(образец)) {
    б.push(`фразы Сергея нет посимвольно. Нашлось: ${строки.map((с) => `«${с.slice(0, 60)}»`).join(', ')}`);
  }
  return б;
};

test('фраза Сергея на карточке QueQuest стоит посимвольно', () => {
  assert.ok(эталон.length > 20, `эталон подозрительно короткий: «${эталон}»`);
  const html = readFileSync(join(корень, 'index.html'), 'utf8');
  assert.deepEqual(беды(html, эталон), []);
});

test('проверка краснеет на подмене', () => {
  const html = readFileSync(join(корень, 'index.html'), 'utf8');
  // Подмена целиком — как было дважды в жизни.
  assert.match(
    беды(html.replace(эталон, 'Вирусы лезут в компьютер, а ты оказываешься внутри защиты.'), эталон)[0] ?? '',
    /нет посимвольно/,
  );
  // Подмена одной буквы: «приглаживание» ловится так же, как замена целиком.
  assert.match(беды(html, эталон.replace('бабки', 'деньги'))[0] ?? '', /нет посимвольно/);
  // И если строк не осталось вовсе.
  assert.match(беды('<p>ничего</p>', эталон)[0] ?? '', /ищем не там/);
});
