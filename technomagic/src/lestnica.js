/* Какая ступень у какого события выдачи. */
export function stepOfUnlock(event) {
  if (event.type !== 'unlock') return null;
  if (event.kind === 'element') return event.element;
  if (event.kind === 'stack') return event.size === 2 ? 'stack2' : event.size === 3 ? 'stack3' : null;
  return null;
}

/*
 * ПОДСКАЗКА ЖИВЁТ В МИРЕ, А НЕ ТОЛЬКО В СТРОКЕ
 * =========================================================
 * Приёмка 03.10, пункт 1: на телефоне 375×812 первая подсказка «СОЖГИ
 * ДЕРЕВЯННЫЕ ВОРОТА» видна, а сами ворота — в одиннадцати клетках правее
 * игрока, за краем кадра. Строка говорила «что», но не «где».
 *
 * Поэтому у каждой ступени есть цель — клетка, — и пока ступень не
 * пройдена, она лежит в мире полем `world.hint`:
 *
 *   { step, text, cell: [x, y], target: { x, y }, aim, since }
 *
 * Мир, а не main.js: её читают и отрисовка сверху (кольцо на цели или
 * стрелка у края экрана, src/ukazatel.js), и автонаводка (aim.js), и
 * будущий объёмный вид — одна правда на всех, и прогон в Node видит её
 * так же. `since` — когда ступень началась, по часам этажа: из него
 * счётчик узнаёт, что человек застрял (ladderTick ниже).
 *
 * `world` в start необязателен: проверкам строк он не нужен.
 */
function hintOf(world, stepName, text) {
  const step = STEPS[stepName];
  if (!world || !step || !step.target) return null;
  const [x, y] = step.target(world);
  return {
    step: stepName,
    text,
    cell: [x, y],
    target: { x: (x + 0.5) * TILE_SIZE, y: (y + 0.5) * TILE_SIZE },
    aim: Boolean(step.aim),
    since: world.time,
  };
}

