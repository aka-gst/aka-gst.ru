/* Дорожка через ров готова: с южного берега до северного ногами. */
export function moatCrossable(world) {
  const { w } = world;
  const seen = new Set();
  const queue = [];
  for (let x = 41; x <= 58; x += 1) {
    const i = 31 * w + x;
    if (!blocksMove(world.tiles[i])) { seen.add(i); queue.push(i); }
  }
  while (queue.length) {
    const i = queue.shift();
    const x = i % w;
    const y = (i / w) | 0;
    if (y <= 27) return true;
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, -1], [0, 1]]) {
      const nx = x + dx;
      const ny = y + dy;
      if (nx < 41 || nx > 58 || ny < 27 || ny > 31) continue;
      const n = ny * w + nx;
      if (seen.has(n) || blocksMove(world.tiles[n])) continue;
      seen.add(n);
      queue.push(n);
    }
  }
  return false;
}

