# есть, а сторож считает её тайной и молчит, если ссылка однажды пропадёт.
#
# way добавлен 6 сентября 2026: страница «Дневника пути» намеренно живёт без
# ссылки с витрины и с noindex — это решение Сергея, названное вслух через
# Мозга: демо показывают при собеседнике, а не выкладывают на витрину.
# Правило 30д такое исключение допускает именно при названном решении, и
# держать его надо списком, а не выключением проверки: новая сирота обязана
# краснеть.
#
# torgash добавлен 6 сентября 2026: страница «Тест на 1000 ₽ — как идёт»,
# снимок с настоящими сделками Сергея. Он попросил её вслух, чтобы смотреть
