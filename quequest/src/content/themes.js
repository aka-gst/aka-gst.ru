const KEY = 'qa-quest.theme';

export function themeById(id) {
  return THEMES.find((theme) => theme.id === id) || THEMES[0];
}

/** Выбранная история. Незнакомое значение молча откатывается к первой. */
export function activeTheme() {
  try {
    return themeById(localStorage.getItem(KEY));
  } catch (_) {
    // Приватный режим может запретить хранилище — это не повод падать.
    return THEMES[0];
  }
}

/**
 * Переключает историю и перезагружает страницу. Перезагрузка здесь честнее
 * частичной перерисовки: содержание ступени меняется целиком, а Python уже
 * лежит в кеше браузера, поэтому второй раз он не качается.
 */
export function setTheme(id) {
  try {
    localStorage.setItem(KEY, themeById(id).id);
  } catch (_) { /* не сохранилось — переживём, откроется история по умолчанию */ }
  location.reload();
}
