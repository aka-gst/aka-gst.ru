// РУЧКИ: первое, что заметит человек, — одной фразой.
export function knobs(v) {
  const r = boardRun(v, { mode: 'board' });
  const start = Number(v.start), pump = Number(v.pump), win = Number(v.window), rain = v.rain === 'да';
  if (start > 30) return { ok: false, why: 'Насос включался, когда земля была ещё влажной, — к пятнице корни загнили.', run: r };
  if (start < 30) return { ok: false, why: 'Плата ждала, пока влажность упадёт до 10, — в понедельник помидоры повесили листья от жажды.', run: r };
  if (pump < 5) return { ok: false, why: 'Насос брызнул минуту и выключился — сверху мокро, а у корней сухо, листья вянут.', run: r };
  if (pump > 5) return { ok: false, why: 'Насос лил полчаса — вода стоит в грядках, корни гниют.', run: r };
  if (win > 28) return { ok: false, why: 'Во вторник в теплице 33 градуса, а окно ждёт сорока — листья сварились, как в бане.', run: r };
  if (win < 28) return { ok: false, why: 'Окно открывается уже при 20 градусах — в прохладный четверг рассаду выстудило.', run: r };
  if (!rain) return { ok: false, why: 'В среду шёл дождь, а насос всё равно качал — рассада в болоте, вода из бочки ушла зря.', run: r };
  return { ok: true, why: 'Плата поливает только сухую землю и понемногу, открывает окно в жару и не мешает дождю. В субботу баба Зина приехала — помидоры стоят ровные.', run: r };
}

