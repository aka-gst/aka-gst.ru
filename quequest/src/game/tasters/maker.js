// повядший жёлтый (сухо), бурый (жара), тёмный с лужей (гниёт), синий (выстудило).
const SOIL = rgb(74, 52, 34), PIPE = rgb(130, 136, 140), WATER = rgb(90, 170, 230);
const LEAF = {
  idle: rgb(80, 170, 80), good: rgb(70, 200, 80), dry: rgb(190, 160, 60), hot: rgb(150, 90, 40),
  rot: rgb(80, 82, 40), swamp: rgb(70, 90, 50), cold: rgb(120, 170, 200),
};
const condOf = (a) => a.cond ?? (a.vars ? { вл: a.vars.влажность, жара: a.vars.жара, дождь: a.vars.дождь } : MAKER_DAYS[0]);
const stateOf = (a) => a.state ?? outcome(a.fate, condOf(a));

function plant(P, x, y, state, time) {
  const leaf = LEAF[state] ?? LEAF.idle, droop = state !== 'good' && state !== 'idle';
  const stem = droop ? rgb(110, 110, 60) : rgb(60, 140, 60);
  if (state === 'rot') P.rect(x - 8, y - 1, 18, 2, rgb(60, 50, 34));
  if (state === 'swamp') { P.rect(x - 11, y - 2, 24, 3, rgb(50, 80, 110)); P.put(x - 6 + (Math.floor(time * 3) % 8), y - 2, WATER); }
  const sway = state === 'good' || state === 'idle' ? Math.round(Math.sin(time * 2 + x) * 0.6) : 0;
  P.rect(x + sway, y - 22, 2, 22, stem);
  for (const ly of [y - 6, y - 12, y - 18]) {
    if (droop) { P.line(x, ly, x - 5, ly + 4, leaf); P.line(x + 1, ly, x + 6, ly + 4, leaf); }
    else { P.line(x + sway, ly, x - 5 + sway, ly - 3, leaf); P.line(x + 1 + sway, ly, x + 6 + sway, ly - 3, leaf); }
  }
  if (state === 'good') { P.disc(x - 3, y - 9, 2, C.red); P.disc(x + 5, y - 15, 2, C.red); P.put(x - 3, y - 12, C.green); }
  else if (state === 'idle') { P.disc(x - 3, y - 9, 1, rgb(140, 200, 90)); P.disc(x + 5, y - 15, 1, rgb(140, 200, 90)); }
  else if (state === 'rot' || state === 'swamp') { P.disc(x - 3, y - 6, 2, rgb(90, 50, 30)); P.put(x - 3, y - 6, rgb(30, 20, 14)); }
  else if (state === 'dry' || state === 'hot') P.disc(x - 3, y - 5, 1, rgb(160, 90, 40));
}
