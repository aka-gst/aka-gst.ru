// Что стало с кустом после действия платы. good — стоит ровный; dry — засох; hot — сварился в
// жаре; rot — корни гниют от перелива; swamp — вода стоит, рассада в болоте; cold — выстудило.
export function outcome(act, cond, pump = 5) {
  const rain = cond.дождь === 'да';
  if (act === 'water') {
    if (rain) return 'swamp';
    if (cond.вл >= 30) return 'rot';
    return pump < 5 ? 'dry' : pump > 5 ? 'rot' : 'good';
  }
  if (act === 'window') return rain ? 'swamp' : cond.жара > 28 ? 'good' : 'cold';
  if (act === 'locked') return 'dry';
  if (!rain && cond.вл < 30) return 'dry';
  if (!rain && cond.жара > 28) return 'hot';
  return 'good';
}
// Плата с ручками: что она сделает в этот день.
function decide(cond, v) {
  if (v.rain === 'да' && cond.дождь === 'да') return 'wait';
  if (cond.вл < Number(v.start)) return 'water';
  if (cond.жара > Number(v.window)) return 'window';
  return 'wait';
}
const actor = (d, act, state) => ({ name: d.name, cond: d, fate: act, state, ok: state === 'good' });
const boardRun = (v, extra = {}) => ({
  actors: MAKER_DAYS.map((d) => { const act = decide(d, v); return actor(d, act, outcome(act, d, Number(v.pump))); }),
  ...extra,
});

