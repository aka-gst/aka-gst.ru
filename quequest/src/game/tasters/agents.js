// РУЧКИ: первое, что заметит человек, — одной фразой.
export function knobs(v) {
  const model = v.reader === 'model', ask = v.unsure === 'ask', table = v.orders === 'table';
  const fates = AGENT_MSGS.map((m) => {
    if (m.kind === 'spam') return 'trash';
    if (m.kind === 'question' && !m.unsure) return 'answer';
    if (m.unsure) return ask ? 'ask' : 'table';
    if (m.hard && !model) return 'answer';                    // нет слова «заказ» — помощник принял за вопрос
    return table ? 'table' : 'chat';
  });
  const r = run(fates, { mode: 'agent' });
  if (!model) return { ok: false, why: '«Букет маме, 2000 ₽» — в нём нет слова «заказ», и помощник ответил на него как на вопрос. Нейросеть понимает смысл, а не одно слово.', run: r };
  if (!table) return { ok: false, why: 'Заказы остались в чате среди двухсот сообщений — к пятнице Вера нашла не все.', run: r };
  if (!ask) return { ok: false, why: '«А пионы есть?» — помощник не понял, вопрос это или заказ, и наугад записал заказ на пионы, которых нет.', run: r };
  return { ok: true, why: 'Нейросеть читает смысл, заказы — в таблице, а в сомнительном случае помощник спрашивает Веру. Ничего не потерялось.', run: r };
}

// КОД: что сказало правило → куда летит сообщение в сцене.
export function fate(c) {
  return { 'В ТАБЛИЦУ': 'table', 'ОТВЕТИТЬ': 'answer', 'В КОРЗИНУ': 'trash', 'СПРОСИТЬ ВЕРУ': 'ask' }[c.got] ?? 'lost';
}

