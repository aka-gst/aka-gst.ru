// ------------------------------------------------------------- сцена
// Слева телефон Веры, сообщения летят по ленте к помощнику и дальше в одну из корзин:
// ТАБЛИЦА (заказы), ОТВЕТ (вопросы), КОРЗИНА (мусор), ВЕРА? (спросить). Шаблон «ТИСКОВ» —
// красная коробка; потерянное падает с ленты.
const BINS = {
  table: [236, 26, 'ТАБЛИЦА', rgb(30, 70, 40), C.green],
  answer: [236, 62, 'ОТВЕТ', rgb(24, 50, 80), C.cyan],
  trash: [236, 98, 'КОРЗИНА', rgb(50, 50, 56), C.dim],
  ask: [180, 120, 'ВЕРА?', rgb(80, 60, 20), C.gold],
  template: [236, 62, 'ТИСКИ-БОТ', rgb(90, 20, 20), C.red],
  chat: [16, 120, 'ЧАТ', rgb(40, 40, 50), C.dim],
};
function bubble(P, x, y, m, open) {
  const col = !open ? C.white : m.kind === 'order' ? rgb(200, 240, 200) : m.kind === 'spam' ? rgb(240, 200, 200) : rgb(200, 225, 245);
  P.rect(x, y, 22, 12, col); P.box(x, y, 22, 12, rgb(90, 90, 100));
  P.rect(x + 3, y + 4, 14, 1, rgb(120, 120, 130)); P.rect(x + 3, y + 7, 10, 1, rgb(120, 120, 130));
}
function bin(P, key, glow) {
  const [x, y, name, fill, ink] = BINS[key];
  P.rect(x, y, 70, 26, fill); P.box(x, y, 70, 26, glow ? ink : rgb(90, 90, 100));
  tag(P, x + 35, y + 3, name, ink);
}
export function paint(P, view) {
  const { time, t, result, actors } = view;
  P.rect(0, TOP, W, BOTTOM - TOP, rgb(30, 26, 34));
  for (let x = 0; x < W; x += 24) P.rect(x, TOP, 1, BOTTOM - TOP, rgb(38, 34, 44));
  tag(P, 160, 18, 'ЛАВКА ВЕРЫ · ЦВЕТЫ', C.gold);
  // телефон Веры
  P.rect(8, 34, 34, 60, rgb(20, 20, 26)); P.box(8, 34, 34, 60, rgb(120, 120, 130)); P.rect(12, 38, 26, 48, rgb(40, 60, 90));
  tag(P, 40, 98, '200 СООБЩЕНИЙ', C.white);
  // лента и помощник посередине
  P.rect(44, 74, 120, 3, rgb(70, 70, 76));
  for (let x = 44; x < 164; x += 8) P.rect(x + ((time * 16) % 8), 75, 3, 1, rgb(110, 110, 116));
  const mode = result?.run?.mode ?? (view.level > 0 ? 'agent' : 'idle');
  if (mode === 'tiski') { P.rect(150, 50, 26, 22, rgb(170, 30, 30)); tag(P, 163, 42, '«ТИСКИ-БОТ»', C.red); }
  else if (mode === 'night') { person(P, 156, 52, rgb(150, 80, 140), { scale: 2 }); tag(P, 161, 42, 'ВЕРА НЕ СПИТ', C.dim); }
  else { P.rect(150, 50, 26, 22, rgb(70, 110, 160)); P.box(150, 50, 26, 22, C.cyan); P.rect(155, 57, 4, 4, C.cyan); P.rect(167, 57, 4, 4, C.cyan); tag(P, 163, 42, 'ПОМОЩНИК', C.cyan); }
  person(P, 186, 128, rgb(150, 80, 140), { scale: 2 }); tag(P, 191, 150, 'ВЕРА', C.gold);
  const used = new Set(actors.map((a) => a.fate));
  for (const k of ['table', 'answer', 'trash']) if (!(mode === 'tiski' && k === 'answer')) bin(P, k, used.has(k));
  if (mode === 'tiski') bin(P, 'template', true);
  if (used.has('ask')) bin(P, 'ask', true);
  if (used.has('chat')) bin(P, 'chat', true);
  if (view.idle) {
    for (let i = 0; i < 5; i++) { const k = (time * 0.25 + i / 5) % 1; bubble(P, lerp(40, 150, k), 62, AGENT_MSGS[i], false); }
    return;
  }
  const stack = {};
  actors.forEach((a, i) => {
    const [ph, k] = phaseOf(i, t); if (ph === 'wait') return;
    const m = AGENT_MSGS.find((x) => x.text === a.name) ?? { kind: a.kind };
    if (ph === 'walk') { bubble(P, lerp(40, 150, k), 62, m, false); return; }
    if (a.fate === 'lost') { const y = lerp(62, 150, ease(k)); bubble(P, 120 + k * 10, y, m, true); wrongMark(P, 131, y + 6, time); return; }
    const b = BINS[a.fate] ?? BINS.trash, n = (stack[a.fate] = (stack[a.fate] ?? 0) + 1) - 1;
    const x = lerp(150, b[0] + 4 + (n % 3) * 22, ease(k)), y = lerp(62, b[1] + 12, ease(k));
    bubble(P, x, y, m, true);
    if (!a.ok) wrongMark(P, x + 11, y + 6, time);
  });
}
