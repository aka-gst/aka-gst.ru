G['Ё'] = G['Е'];
const LATIN = { A: 'А', B: 'В', C: 'С', E: 'Е', H: 'Н', K: 'К', M: 'М', O: 'О', P: 'Р', T: 'Т', X: 'Х' };
const ROWS = new Map();
for (const [ch, bits] of Object.entries(G)) {
  ROWS.set(ch, bits.split('|'));
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;

export function glyph(ch) {
  const up = String(ch).toUpperCase();
  return ROWS.get(up) ?? ROWS.get(LATIN[up]) ?? null;
}

export function textWidth(text, scale = 1) {
  return Math.max(0, String(text).length * ADVANCE * scale - scale);
}

// Draws into a Uint32Array frame buffer (ABGR). A 1px dark drop shadow keeps
// the text readable over any texture, like Doom's HUD messages.
export function drawText(buf, width, height, x, y, text, color, { scale = 1, shadow = 0xff000000 } = {}) {
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of String(text)) {
    const rows = glyph(ch);
    if (rows) {
      for (let r = 0; r < 7; r++) {
        const row = rows[r];
        for (let c = 0; c < 5; c++) {
          if (row[c] !== '#') continue;
          for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) {
            const px = cx + c * scale + sx;
            const py = cy + r * scale + sy;
            if (shadow && px + scale < width && py + scale < height && px + scale >= 0 && py + scale >= 0) {
              const si = (py + scale) * width + px + scale;
              if (buf[si] !== color) buf[si] = shadow;
            }
            if (px >= 0 && py >= 0 && px < width && py < height) buf[py * width + px] = color;
          }
        }
      }
    }
    cx += ADVANCE * scale;
  }
}
